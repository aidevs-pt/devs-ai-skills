"""Generate catalogs, plugin manifests, and domain indexes; optionally export local website content."""
from __future__ import annotations
import argparse
import html
import json
from pathlib import Path
from repo import ROOT, catalog, identity, json_text, read_json, write


def outputs(root=ROOT, *, include_website=False):
    cfg = identity(root)
    skills = catalog(root)
    bundles = read_json(root / 'bundles.json')
    names = {s['name'] for s in skills}
    for key, members in bundles.items():
        if not members or len(set(members)) != len(members) or set(members) - names:
            raise ValueError(f'Invalid bundle membership: {key}')
    registry = {'schema_version':1,'version':cfg['version'],'publisher':cfg['publisher'],
                'skills':skills,'bundles':bundles,'skill_count':len(skills)}
    generated = {'registry.json':json_text(registry),'skills.json':json_text(skills),
                 'cli/skills.json':json_text(registry)}
    for target in ['.codex/skills-index.json','.gemini/skills-index.json']:
        generated[target]=json_text({'source':'registry.json','skills':[{'name':s['name'],'description':s['description'],'path':s['path']} for s in skills]})
    plugin={'name':'devs-ai-business-skills','version':cfg['version'],
            'description':'Practical file-based business workflows for commerce, support, knowledge, and operations.',
            'author':{'name':cfg['publisher'],'url':cfg['website']},'homepage':cfg['website'],
            'license':cfg['license'],'skills':['./.agents/skills/']}
    if cfg.get('github_repository'):
        plugin['repository']='https://github.com/'+cfg['github_repository']
    generated['.claude-plugin/plugin.json']=json_text(plugin)
    generated['.claude-plugin/marketplace.json']=json_text({'name':'devs-ai-marketplace',
      'owner':{'name':cfg['publisher'],'url':cfg['website']},'plugins':[{
       'name':plugin['name'],'source':'./','description':plugin['description']}]})
    generated['.codex-plugin/plugin.json']=json_text({**plugin,'skills':'./.agents/skills/',
      'interface':{'displayName':'DEVS AI Skills','shortDescription':'Business workflows with AI',
       'longDescription':f'{len(skills)} business workflows with local helper tools and examples. Use supplied files to prepare business outputs. Native client loading and model quality need validation in the selected environment.',
       'developerName':'DEVS AI','category':'Productivity','websiteURL':cfg['website']}})
    category_rows={}
    for s in skills:
        category_rows.setdefault(s['category'],[]).append(s)
        if not include_website:continue
        slug=s['name']
        meta={'title':s['website_title'],'description':s['summary'],'slug':slug,
              'primary_query':s['primary_query'],'keywords':s['keywords'],
              'proposed_path':'/skills/'+slug+'/','published':False,'skill_version':s['version']}
        front='---\n'+'\n'.join(k+': '+json.dumps(v,ensure_ascii=False) for k,v in meta.items())+'\n---\n'
        install=(f"npx skills add {cfg['github_repository']} --skill {slug}" if cfg.get('github_repository') else
                 f'python scripts/devs.py install {slug} --agent claude --scope project --project /path/to/your/project')
        page=f'''# {s['title']}

{s['summary']}

For {s['audience'].lower()}. This is a free, downloadable agent skill used in your own assistant; it is not a hosted web application.

## What you receive

{s['free_result']}

## Try a complete example

Open `{s['path']}/assets/example-input.json` and its worked helper output.
Ask your assistant to use this skill and produce the actual requested business artifact.
Synthetic examples can be used without giving us business data or connecting an account.

{s['differentiator']}

## Install

After extracting or cloning this repository, use the local installer or copy this one skill folder.

```bash
{install}
```

Claude Code, Codex, Cursor, Copilot, and Gemini CLI have documented skill paths; see the compatibility guide for loading and verification details.
The skill is MIT-licensed. Your chosen AI host, model access, or optional integrations may have separate costs.

## What is verified

Bundled helpers run locally and have executable example checks. Language quality and business rules still need review on your records.

## When a connected implementation would help

{s['paid_moment']}

DEVS AI can discuss {s['service_bridge'][0].lower()+s['service_bridge'][1:]}
The free workflow remains useful without contacting us. [Discuss this workflow]({cfg['services_url']}).

## Related public work

'''+ '\n'.join(f'- [Public service/case reference]({url})' for url in s['case_studies'])+'\n'
        generated[f'website/content/skills/{slug}.md']=front+page
    generated['docs/skills-reference.md']='# Skill catalog\n\nGenerated by `scripts/build_manifest.py`.\n\n| Skill | Category | Business job |\n|---|---|---|\n'+''.join(f"| [{s['title']}](../{s['path']}/SKILL.md) | {s['category']} | {s['summary']} |\n" for s in skills)
    for category,items in category_rows.items():
        generated[f'docs/domains/{category}.md']='# '+category.replace('-',' ').title()+'\n\n'+''.join(f"- [{s['title']}](../../{s['path']}/SKILL.md): {s['summary']}\n" for s in items)
    if include_website:
        generated['website/content/index.md']='# Free AI skills for business work\n\nUse these workflows with your own assistant. Choose a job, inspect the example, and install only what you need.\n\n'+''.join(f"- [{s['title']}](skills/{s['name']}.md): {s['summary']}\n" for s in skills)
    return generated


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Report drift without writing')
    parser.add_argument('--include-website',action='store_true',help='Also generate/check ignored local website content')
    args=parser.parse_args()
    mismatches=[]
    for name,text in outputs(include_website=args.include_website).items():
        path=ROOT/name
        if not path.exists() or path.read_text(encoding='utf-8') != text:
            mismatches.append(name)
            if not args.check:write(path,text)
    if args.check and mismatches:
        command='python scripts/build_manifest.py'+(' --include-website' if args.include_website else '')
        parser.exit(1,'Generated files are stale:\n'+'\n'.join(mismatches)+'\nRun '+command+'\n')
    print(f'{"Checked" if args.check else "Generated"} catalogs/pages; {len(mismatches)} {"mismatches" if args.check else "files updated"}.')


if __name__=='__main__':main()
